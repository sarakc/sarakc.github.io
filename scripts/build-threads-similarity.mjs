#!/usr/bin/env node
/* Build the similarity edges for a /threads collection and write them next
   to it: items.json → items.similarity.json. The page reads that file when it
   exists and falls back to shared-tag edges when it doesn't.

     npm run build-similarity                      # public/threads/items.json
     npm run build-similarity -- drafts/threads-research.json

   Also prints pairs whose titles look like the same work but whose `project`
   keys don't say so — worth a look when adding items. */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve, relative } from 'node:path'
import { buildSimilarity, projectSuggestions, describeReasons, DEFAULTS } from '../src/components/threads/similarity.mjs'
import { similarityEdges } from '../src/components/threads/graph.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const input = process.argv[2]
  ? resolve(process.cwd(), process.argv[2])
  : resolve(root, 'public', 'threads', 'items.json')
const output = input.replace(/\.json$/, '.similarity.json')

const { items } = JSON.parse(await readFile(input, 'utf8'))
const usable = items.filter(i => i && i.id)
const edges = buildSimilarity(usable, DEFAULTS)

await writeFile(output, JSON.stringify({
  about: `Generated by scripts/build-threads-similarity.mjs from ${relative(root, input)}. Do not edit by hand.`,
  config: DEFAULTS,
  edges,
}, null, 1) + '\n')

/* What the page draws with everything shown: each item's best k. */
const drawn = similarityEdges(usable, edges, DEFAULTS.k)
const degree = new Map(usable.map(i => [i.id, 0]))
for (const e of drawn) { degree.set(e.source, degree.get(e.source) + 1); degree.set(e.target, degree.get(e.target) + 1) }
const isolated = [...degree].filter(([, d]) => d === 0).map(([id]) => id)

console.log(`\n${usable.length} items → ${edges.length} candidate pairs (${drawn.length} drawn at full detail) → ${relative(root, output)}\n`)
const strongest = [...drawn].sort((a, b) => b.score - a.score).slice(0, 8)
console.log('strongest:')
for (const e of strongest) console.log(`  ${e.score.toFixed(2)}  ${e.source} — ${e.target}  (${describeReasons(e.reasons).join(', ')})`)
if (isolated.length) console.log(`\nno neighbour: ${isolated.join(', ')}`)

const hints = projectSuggestions(usable)
if (hints.length) {
  console.log('\nsame work? titles are close but `project` differs or is missing:')
  for (const h of hints) console.log(`  ${h.title.toFixed(2)}  ${h.a} (${h.projects[0]}) ~ ${h.b} (${h.projects[1]})`)
}
console.log('')
